"""Verify the Lua Language Server meta bundle really is the Factorio 2.1.23 API.

The LuaLS bundle is generated by ``fmtk docs`` from the offline 2.1.23 API
JSON. Without it, LuaLS cannot check a single Factorio API signature: it
reports every Factorio global as undefined and silently passes everything else.

These tests are offline and CPU-only. They do not run Factorio.
"""
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = ROOT / ".local" / "factorio-api-offline" / "2.1.23"
FILES = ARCHIVE / "files"
BUNDLE = ARCHIVE / "luas-addon" / "factorio" / "library"
CONFIG = ROOT / "tests" / "lua_diagnostics_probe.lua"


class Factorio2123LuaLSBundle(unittest.TestCase):
    """The generated meta bundle must correspond to the 2.1.23 API archive."""

    def test_bundle_exists_and_is_populated(self):
        self.assertTrue(BUNDLE.is_dir(), f"missing LuaLS meta bundle: {BUNDLE}")
        lua_files = list(BUNDLE.rglob("*.lua"))
        self.assertGreater(len(lua_files), 100, "meta bundle looks empty")

    def test_bundle_declares_factorio_2_1_23(self):
        headers = set()
        for path in BUNDLE.rglob("*.lua"):
            text = path.read_text(encoding="utf-8", errors="replace")
            if "$Factorio " in text:
                for line in text.splitlines():
                    if line.startswith("--$Factorio "):
                        headers.add(line.strip())
        self.assertIn("--$Factorio 2.1.23", headers)

    def test_bundle_documentation_links_are_pinned_to_2_1_23(self):
        """A stale bundle would still link to the old /2.1.22/ doc base."""
        text = ""
        for path in list(BUNDLE.rglob("*.lua"))[:200]:
            text += path.read_text(encoding="utf-8", errors="replace")
        self.assertIn("https://lua-api.factorio.com/2.1.23/", text)
        self.assertNotIn("https://lua-api.factorio.com/2.1.22/", text)
        self.assertNotIn("https://lua-api.factorio.com/2.0.77/", text)

    def test_bundle_declares_factorio_runtime_globals(self):
        """The bundle must define the runtime globals the mod uses."""
        text = ""
        for path in list(BUNDLE.rglob("*.lua"))[:400]:
            text += path.read_text(encoding="utf-8", errors="replace")
        for symbol in ("LuaGameScript", "LuaBootstrap", "LuaSurface", "LuaEntity"):
            self.assertIn(symbol, text)

    def test_config_points_at_the_2123_bundle_with_absolute_path(self):
        self.assertTrue(CONFIG.is_file())
        config = CONFIG.read_text(encoding="utf-8")
        self.assertIn("2.1.23/luas-addon/factorio/library", config)
        # A relative --configpath is silently ignored by LuaLS during --check.
        self.assertIn("d:/AI/Factorio-AutoEngineer-Source", config)
        self.assertNotIn("${workspaceFolder}/.local/factorio-api-offline/2.1.22", config)

    def test_bundle_matches_archive_api_version(self):
        runtime = json.loads((FILES / "runtime-api.json").read_text(encoding="utf8"))
        self.assertEqual(runtime["application_version"], "2.1.23")


if __name__ == "__main__":
    unittest.main()
